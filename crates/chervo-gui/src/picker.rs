//! Выбор папки системным диалогом (`rfd`). Только выбор пути: GUI сам ничего не создаёт и не
//! записывает. На Linux диалог идёт через портал рабочего стола (без установки пакетов); если
//! портала нет, `None`, и пользователь вводит путь вручную.

use std::path::PathBuf;

pub fn pick_folder() -> Option<PathBuf> {
    rfd::FileDialog::new().pick_folder()
}
