/// Размер для экрана: «512 Б», «1,5 ГБ» (основание 1024, одна цифра после запятой).
fn human_size(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["Б", "КБ", "МБ", "ГБ", "ТБ"];
    let mut value = bytes;
    let mut frac = 0u64;
    let mut unit = 0usize;
    while value >= 1024 && unit + 1 < UNITS.len() {
        frac = (value % 1024) * 10 / 1024;
        value /= 1024;
        unit += 1;
    }
    let name = UNITS.get(unit).copied().unwrap_or("ТБ");
    if unit == 0 {
        format!("{value} {name}")
    } else {
        format!("{value},{frac} {name}")
    }
}

/// Предупреждение «не хватает места» с обоими числами (Рев. 5): сколько нужно (предложение
/// плюс запас) и сколько есть (за вычетом остальных приёмов). Путей и имён в тексте нет.
pub fn insufficient_space_text(s: &SpaceShortfall) -> String {
    format!(
        "Не хватает места для приёма: нужно {}, свободно {} (с учётом других приёмов и запаса). {}",
        human_size(s.needed),
        human_size(s.available),
        CHOOSE_OTHER_FOLDER_TEXT
    )
}
