//! Ошибки чистых модулей: перечисление без текста (байты датаграмм в ошибки не попадают).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum LanError {
    /// Источник случайных чисел ОС недоступен: ничего не отправляется.
    Random,
    /// Слот не собрать (порт 0 или сбой примитива).
    Crypto,
}
